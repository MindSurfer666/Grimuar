#!/bin/bash

# 📍 Путь до файла
ICS_PATH="./calendar.ics"

# 🧪 Проверим наличие файла
if [ ! -f "$ICS_PATH" ]; then
  echo "❌ Файл $ICS_PATH не найден!"
  exit 1
fi

# 📂 Откроем файл через системное приложение
echo "📤 Импортируем $ICS_PATH в Календарь macOS..."
open "$ICS_PATH"

# 📝 Подсказка
echo "✅ Календарь откроется, нажми «Добавить» для подтверждения."